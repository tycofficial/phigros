'use strict';
// Real browser integration. Run with Playwright on NODE_PATH and a local site server.
const {chromium}=require('playwright'),assert=require('node:assert/strict');
(async()=>{const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--autoplay-policy=no-user-gesture-required','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});try{const page=await browser.newPage({viewport:{width:1280,height:720}}),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>localStorage.setItem('phi.visionReplayEnabled','false'));
  await page.goto((process.argv[2]||'http://127.0.0.1:8784')+'/?skipIntro');
  await page.waitForFunction(()=>window.PhiInteractiveReplay&&window.PhiVisionMode);
  await page.evaluate(()=>document.querySelector('[data-reference-open-library]').click());
  await page.waitForSelector('#libraryView:not(.hidden)');
  await page.evaluate(()=>{const s=document.querySelector('#librarySearch');s.value='Luminescence';s.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('.card h3')).some(e=>e.textContent==='Luminescence'));
  console.log('catalog-ready');
  await page.evaluate(()=>{const card=Array.from(document.querySelectorAll('.card')).find(c=>c.querySelector('h3')?.textContent==='Luminescence');card.click();card.querySelectorAll('.difficultyOption')[2].click();card.querySelector('.play').click();});
  await page.waitForFunction(()=>window.__phiEngine?.running&&!window.__phiEngine.paused,{},{timeout:120000});
  console.log('engine-ready');
  await page.evaluate(async()=>{const e=__phiEngine;e.setAutoplay(true);e.setPlaybackRate(8);
  await e.startMusic(e.musicCurrentTime());});
  await page.waitForFunction(()=>__phiEngine?.lumiInSongRenderer?.stats.particleCount>0,{},{timeout:60000});
  const pass=await page.evaluate(()=>({time:__phiEngine.musicCurrentTime(),mode:PhiVisionMode.enabled,state:__phiEngine.lumiInSongFrame,stats:__phiEngine.lumiInSongRenderer.stats,raw:__phiEngine.rawScore(),counts:__phiEngine.counts.slice(),replay:PhiInteractiveReplay.current,visible:document.elementFromPoint(640,360)?.closest('#gameView')?.id}));
  console.log('success',JSON.stringify(pass));
  assert.equal(pass.visible,'gameView');
  assert.equal(pass.mode,false);
  assert.equal(pass.replay,null);
  assert.equal(pass.state.stage1Failed,false);
  assert.equal(pass.state.stage2Failed,false);
  assert(pass.stats.particleCount>0);
  await page.screenshot({path:'/tmp/luminescence-ordinary-success.png'});
  await page.waitForFunction(()=>!__phiEngine.running,{},{timeout:15000});
  assert.equal(await page.evaluate(()=>PhiInteractiveReplay.current),null);
  assert.equal(await page.evaluate(()=>__phiEngine.lumiInSongFrame.songKey),'luminescence');
  assert.deepEqual(errors,[]);
  console.log('ordinary success and normal finish passed');
  await page.evaluate(async()=>{const e=__phiEngine;e.setAutoplay(false);
  await e.restart();e.setPlaybackRate(8);
  await e.startMusic(e.musicCurrentTime());});
  await page.waitForFunction(()=>__phiEngine.musicCurrentTime()>135&&__phiEngine.lumiInSongFrame?.time>134,{},{timeout:60000});
  const failed=await page.evaluate(()=>({state:__phiEngine.lumiInSongFrame,stats:__phiEngine.lumiInSongRenderer.stats,counts:__phiEngine.actualCounts.slice(),replay:PhiInteractiveReplay.current,visible:document.elementFromPoint(640,360)?.closest('#gameView')?.id}));
  console.log('failure',JSON.stringify(failed));
  assert.equal(failed.state.stage1Failed,true);
  assert.equal(failed.state.stage2Failed,true);
  assert.equal(failed.stats.particleCount,0);
  assert(failed.counts[3]>0);
  assert.equal(failed.replay,null);
  assert.equal(failed.visible,'gameView');
  assert.deepEqual(errors,[]);
  console.log('ordinary restart, actual-Miss failure gate and no success particles passed');}finally{await browser.close();}})().catch(e=>{console.error(e);process.exitCode=1;});
