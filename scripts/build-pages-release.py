#!/usr/bin/env python3
"""Build a complete-bundle GitHub Pages subset without changing the full catalog.

Preserve every pre-catalog asset, original audio/art quality, all available tiers,
compact audio variants and previews for each selected song. Required Chapter 8,
Chapter 9 and SP bundles are followed by the smallest remaining complete bundles
(maximum song count for this fixed budget). No transcoding or chart edits occur.
"""
import argparse
from collections import defaultdict
import hashlib
import json
import os
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]
CATALOG_HEADER = '/* Pages subset generated by scripts/build-pages-release.py. */\nglobalThis.PhiFullCatalog='


def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'))


def read_catalog(path):
    text = path.read_text()
    return json.loads(text.split('globalThis.PhiFullCatalog=', 1)[1].rsplit(';', 1)[0])


def references(value):
    result = set()
    if isinstance(value, str) and value.startswith('./assets/'):
        result.add(value[2:])
    elif isinstance(value, dict):
        for child in value.values():
            result.update(references(child))
    elif isinstance(value, list):
        for child in value:
            result.update(references(child))
    return result


def copy_file(source, target, binary=False):
    target.parent.mkdir(parents=True, exist_ok=True)
    if binary:
        try:
            os.link(source, target)
            return
        except OSError:
            pass
    shutil.copy2(source, target)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT)
    parser.add_argument('--output', type=Path, default=Path('/workspace/phigros-pages-release'))
    parser.add_argument('--max-bytes', type=int, default=990_000_000)
    args = parser.parse_args()
    source, output = args.source.resolve(), args.output.resolve()
    if output == source or source in output.parents:
        raise SystemExit('Output must be isolated from the full source checkout')
    if output.exists() and any(output.iterdir()):
        raise SystemExit('Output must be an empty directory; choose a new output path')
    output.mkdir(parents=True, exist_ok=True)
    catalog = read_catalog(source / 'js/full-catalog.js')
    assets = {item['id']: item for item in catalog['assets']}
    app = (source / 'js/app.js').read_text()
    existing = json.loads(re.search(r'const BUILTIN_PACKS\s*=\s*(\[.*?\]);', app, re.S)[1])
    bundles = defaultdict(list)
    for entry in catalog['entries']:
        bundles[entry['audioHash']].append(entry)
    bundle_specs = {}
    for song, entries in bundles.items():
        ids = {file['asset'] for entry in entries for file in entry['files']}
        audio_ids = {file['asset'] for entry in entries for file in entry['files'] if file['name'] == entry['meta']['music']}
        art_ids = {file['asset'] for entry in entries for file in entry['files'] if file['name'] == entry['meta']['illustration']}
        files = references([assets[ident] for ident in ids])
        files.update(references([catalog['audio'][ident] for ident in audio_ids]))
        files.update(references([catalog['artwork'][ident] for ident in art_ids]))
        files.update(references([entry.get('thumbnailData') for entry in entries]))
        for path in files:
            if not (source / path).is_file():
                raise SystemExit('Missing bundle dependency: ' + path)
        bundle_specs[song] = {'entries': entries, 'assets': ids, 'audio': audio_ids, 'artwork': art_ids,
                              'files': files, 'bytes': sum((source / path).stat().st_size for path in files),
                              'required': any(entry['meta'].get('collectionId') in {'chapter-8', 'chapter-9', 'special'} or entry['meta'].get('difficultyClass') == 'SP' for entry in entries),
                              'order': min((entry['meta'].get('collectionOrder', 999), entry['meta'].get('songOrder', 999)) for entry in entries)}
    # All old assets survive, including export and original-media paths. Code and
    # source notices are copied separately so generated files cannot modify the
    # full checkout through a hard link.
    base_files = []
    for path in sorted(source.rglob('*')):
        if not path.is_file():
            continue
        rel = path.relative_to(source)
        if rel.parts[0] in {'.git', 'tests'} or '__pycache__' in rel.parts:
            continue
        if len(rel.parts) > 1 and rel.parts[0] == 'assets' and rel.parts[1] in {'catalog-charts', 'catalog-media'}:
            continue
        if str(rel) in {'js/full-catalog.js', 'assets/meta/catalog-coverage.json', 'README.md'}:
            continue
        base_files.append(rel)
    base_bytes = sum((source / path).stat().st_size for path in base_files)
    # Reserve metadata and documentation space before choosing binary bundles.
    # Their actual sizes are checked at the end; a small final bundle may then
    # fill the remaining measured space without weakening any media quality.
    reserve = 2_500_000
    available = args.max_bytes - base_bytes - reserve
    required = sorted((song for song, spec in bundle_specs.items() if spec['required']), key=lambda song: bundle_specs[song]['order'])
    selected, used = [], 0
    for song in required:
        spec = bundle_specs[song]
        if used + spec['bytes'] > available:
            raise SystemExit('Required Chapter 8/9/SP bundles exceed the budget')
        selected.append(song)
        used += spec['bytes']
    for song in sorted((song for song in bundles if song not in selected), key=lambda song: (bundle_specs[song]['bytes'], bundle_specs[song]['order'], song)):
        size = bundle_specs[song]['bytes']
        if used + size <= available:
            selected.append(song)
            used += size
    selected_set = set(selected)

    def subset_for(selected_set):
        entries = [entry for entry in catalog['entries'] if entry['audioHash'] in selected_set]
        ids = set().union(*(bundle_specs[song]['assets'] for song in selected_set)) if selected_set else set()
        audio_ids = set().union(*(bundle_specs[song]['audio'] for song in selected_set)) if selected_set else set()
        art_ids = set().union(*(bundle_specs[song]['artwork'] for song in selected_set)) if selected_set else set()
        song_ids = {entry['audioHash'].removeprefix('reference-song:') for entry in [*existing, *entries]}
        assignments = {song: spec for song, spec in catalog['collectionAssignments'].items() if song in song_ids}
        group_ids = {entry['meta']['collectionId'] for entry in entries}
        group_ids.update(spec['collectionId'] for spec in assignments.values())
        # Existing Message SP is assigned to the SP group by catalog-runtime.
        if any(entry['meta'].get('difficultyClass') == 'SP' for entry in existing):
            group_ids.add('special')
        coverage = dict(catalog['coverage'])
        coverage.update({'addedSongs': len(selected_set), 'addedCharts': len(entries), 'historicalSPChartsAdded': sum(entry['audioHash'].startswith('reference-song:historical-sp:') for entry in entries),
                         'playableCharts': len(existing) + len(entries), 'playableSongVersions': len(song_ids), 'visibleCollections': len(group_ids),
                         'releaseType': 'github-pages-subset', 'fullSourcePlayableCharts': catalog['coverage']['playableCharts'],
                         'fullSourceSongVersions': catalog['coverage']['playableSongVersions'],
                         'omittedSongVersionsForHostingBudget': len(bundles) - len(selected_set),
                         'publishedSourceChartIDs': [entry['id'] for entry in entries],
                         'allHistoricalAprilFools': False, 'chapterStoryAnimationsIncluded': False})
        return {**catalog, 'entries': entries, 'assets': [asset for asset in catalog['assets'] if asset['id'] in ids],
                'audio': {ident: spec for ident, spec in catalog['audio'].items() if ident in audio_ids},
                'artwork': {ident: spec for ident, spec in catalog['artwork'].items() if ident in art_ids},
                'collections': [spec for spec in catalog['collections'] if spec['id'] in group_ids],
                'collectionAssignments': assignments, 'coverage': coverage}

    subset = subset_for(selected_set)
    for path in base_files:
        copy_file(source / path, output / path, binary=path.parts[0] == 'assets')
    selected_files = set().union(*(bundle_specs[song]['files'] for song in selected_set)) if selected_set else set()
    for path in sorted(selected_files):
        if not (output / path).exists():
            copy_file(source / path, output / path, binary=True)
    coverage = subset['coverage']
    (output / 'js/full-catalog.js').write_text(CATALOG_HEADER + compact(subset) + ';\n')
    report = {'version': subset['version'], 'source': subset['source'], **coverage}
    (output / 'assets/meta/catalog-coverage.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    # Explain the deployed subset visibly, without placing a banner over gameplay.
    index = (output / 'index.html').read_text()
    banner = f'<p class="pagesReleaseSummary" style="position:absolute;top:10px;left:70px;right:70px;text-align:center;font-size:12px;color:#ddd;pointer-events:none">4.0.1.2 · Pages 曲库：{coverage["playableSongVersions"]} 个歌曲／版本 · {coverage["playableCharts"]} 张谱面</p>'
    index = re.sub(r'(<section id="refCollection"[^>]*>)', lambda match: match[1] + '\n' + banner, index, count=1)
    index = index.replace('4.0.1.2-catalog-1', '4.0.1.2-pages-9')
    (output / 'index.html').write_text(index)
    for path in ['js/app.js', 'js/hosted-media.js', 'sw.js']:
        file = output / path
        file.write_text(file.read_text().replace('4.0.1.2-catalog-1', '4.0.1.2-pages-9').replace('tycphigros-app-catalog-1', 'tycphigros-app-pages-9'))
    readme = f'''# TYCPHIGROS 4.0.1.2 · GitHub Pages 发布曲库

此发布包含 **{coverage['playableSongVersions']} 个歌曲／活动版本、{coverage['playableCharts']} 张谱面**，共 {coverage['visibleCollections']} 个有内容的章节与精选集分类。完整开发资源库是 335 个版本、1064 张谱面；本次因 Pages 站点容量而发布其中可完整容纳的部分。页面仅显示随站点实际发布的资源，未发布歌曲不会作为可玩条目出现。

保留全部原有 12 首／46 张谱面；优先保留第八章、第九章和全部已取得的历史 SP，再按完整歌曲资源包大小选择可容纳数量最多的歌曲。每个选择的歌曲包含其所有已取得难度／随机变体、原始 OGG、原始高清曲绘、Opus／AAC 省流音轨及渐进预览；没有为增加数量再次降低原音轨或原图质量。音乐与谱面在开歌时按需读取，缩略图仅在可见时读取。

课题模式及独立章节／精选集筛选已包含。仍未收齐全部历年愚人节 SP，尚无完整第八、九章意象动画和原版重演，未声称原版 1:1。来源和具体缺口见 [CATALOG-SOURCES.md](CATALOG-SOURCES.md)。

## 发布和复建

本目录可直接作为现有 GitHub Pages 的 main 分支根目录发布，保留 `.nojekyll`。从包含全部已验证资源的完整开发目录运行：

```sh
python scripts/build-pages-release.py --source /workspace/phigros --output /workspace/phigros-pages-release --max-bytes 990000000
```

输出必须为新的空目录。脚本不会修改完整开发目录；它按歌曲整体选择资源，过滤目录并验证所有引用，生成 `assets/meta/pages-release.json` 和实际覆盖报告。Pages 平台总上限以其当时规则为准；此脚本使用小于十进制 1GB 的站点文件预算。

所有新谱面已在完整资源构建中通过现有解析器和原始字节哈希检查；此发布另核对每个被引用文件都存在且长度符合清单。音频校验报告覆盖完整开发资源库，发布只是选择原文件子集。浏览器真机及官方客户端逐曲／逐帧对照尚未进行。
'''
    (output / 'README.md').write_text(readme)
    report_path = output / 'assets/meta/pages-release.json'
    release_report = {'version': '4.0.1.2-pages-9', 'maxBytes': args.max_bytes, 'baseBytes': base_bytes, 'selectedBundleBytes': used,
                      'selectedNewSongVersions': len(selected_set), 'publishedSongVersions': coverage['playableSongVersions'],
                      'publishedCharts': coverage['playableCharts'], 'visibleCollections': coverage['visibleCollections'],
                      'requiredNewBundles': len(required), 'omittedNewSongVersions': len(bundles) - len(selected_set),
                      'songs': coverage['playableSongVersions'], 'charts': coverage['playableCharts'], 'addedSongs': len(selected_set), 'addedCharts': len(subset['entries']),
                      'selection': 'complete chapter8/chapter9/SP priority, then smallest complete bundles',
                      'originalQualityPreserved': True, 'selectionPolicy': 'required chapter8/chapter9/SP, then smallest complete song bundles',
                      'selectedAudioHashes': selected, 'sourceCoverage': catalog['coverage']}
    report_path.write_text(json.dumps(release_report, ensure_ascii=False, indent=2) + '\n')
    for path in references([subset['assets'], subset['audio'], subset['artwork'], [entry.get('thumbnailData') for entry in subset['entries']]]):
        if not (output / path).is_file():
            raise SystemExit('Published catalog has missing dependency: ' + path)
    for spec in subset['assets']:
        file = output / spec['url'][2:]
        expected = spec.get('byteLength', spec.get('usize'))
        if file.stat().st_size != expected:
            raise SystemExit('Asset length mismatch: ' + str(file))
    # The report records its own eventual size. Iterate once for digit growth.
    for _ in range(3):
        total = sum(path.stat().st_size for path in output.rglob('*') if path.is_file())
        release_report['releaseBytes'] = total
        release_report['bytes'] = total
        release_report['headroomBytes'] = args.max_bytes - total
        report_path.write_text(json.dumps(release_report, ensure_ascii=False, indent=2) + '\n')
    total = sum(path.stat().st_size for path in output.rglob('*') if path.is_file())
    if total > args.max_bytes:
        raise SystemExit(f'Release over budget: {total} > {args.max_bytes}')
    print(json.dumps({key: value for key, value in release_report.items() if key not in {'selectedAudioHashes', 'sourceCoverage'}}, ensure_ascii=False, indent=2))
    print('Output:', output)


if __name__ == '__main__':
    main()
